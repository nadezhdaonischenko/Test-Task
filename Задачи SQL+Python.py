def correct_price(price):
  if price is None:
    return 0

  if '$' in price:
    currency = 'USD'
  elif '€' in price:
    currency = 'EUR'

  price = price.replace('$', '').replace('€', '')

  price = str(price).strip()

  if ',' in price and '.' in price:
    if price.find(',') < price.find('.'):
      price = price.replace(',', '')
    else:
      price = price.replace('.', '').replace(',', '.')

  elif ',' in price:
    price = price.replace(',', '.')

  if price in ['invalid', 'NaN', 'error_val', 'bad_data', 'test', 'broken', 'null', 'N/A']:
    return 0

  corr_price = float(price)

  if currency == 'EUR':
    corr_price = 1.1 * corr_price

  return corr_price


def revenue(transactions):
  total_revenue = 0
  for trans in transactions:
    total_revenue += correct_price(trans['price'])
  return total_revenue

